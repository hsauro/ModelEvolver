//! Antimony export, and a round-trip check of the exported text through the
//! `antimony` crate (feature `antimony`, on by default).

use std::collections::BTreeMap;
use std::fmt::Write as _;

use crate::config::{EvolverConfig, ObjectiveKind};
use crate::ga::ExperimentResult;
use crate::network::{Network, SpeciesStatus};
use crate::objective::RunContext;

pub const VERSION: &str = env!("CARGO_PKG_VERSION");

pub fn species_name(i: usize) -> String {
    format!("S{i}")
}

fn participant(net: &Network, s: u16) -> String {
    let i = s as usize;
    if net.status[i] == SpeciesStatus::Float { species_name(i) } else { format!("${}", species_name(i)) }
}

/// The reactions, initial values and rate constants of `net` as Antimony.
pub fn network_antimony(net: &Network, init: &[f64]) -> String {
    let mut s = String::new();
    for (j, r) in net.reactions.iter().enumerate() {
        let lhs: Vec<String> = r.reactants().iter().map(|&x| participant(net, x)).collect();
        let rhs: Vec<String> = r.products().iter().map(|&x| participant(net, x)).collect();
        let mut law = format!("k{j}");
        for &x in r.reactants() {
            law.push('*');
            law.push_str(&species_name(x as usize));
        }
        let _ = writeln!(s, "J{j}: {} -> {}; {law};", lhs.join(" + "), rhs.join(" + "));
    }
    s.push('\n');
    let used: Vec<usize> = (0..net.n_species).filter(|&i| net.status[i] != SpeciesStatus::Orphan).collect();
    let inits: Vec<String> = used.iter().map(|&i| format!("{} = {};", species_name(i), init[i])).collect();
    s.push_str(&inits.join(" "));
    s.push_str("\n\n");
    for (j, r) in net.reactions.iter().enumerate() {
        let _ = writeln!(s, "k{j} = {};", r.k);
    }
    s
}

/// The full export for an experiment result: header comments, the reduced
/// model, and an optional Tellurium harness.
pub fn to_antimony(r: &ExperimentResult, cfg: &EvolverConfig, ctx: &RunContext) -> String {
    let mut h = String::new();
    let mut c = |line: String| {
        h.push_str("// ");
        h.push_str(&line);
        h.push('\n');
    };
    c(format!("Generated by ModelEvolver (Rust) version {VERSION}"));
    c(format!("Seed = {}, experiment = {}", r.base_seed, r.id));
    c(format!("Solver: diffsol BDF, rtol = {}, atol = {}", cfg.rtol, cfg.atol));
    match cfg.objective {
        ObjectiveKind::Oscillation => {
            c("Objective: sustained oscillation (F = acf*harmonic*sustained*amplitude), fitness = 1 - F".into());
            c(format!("Evolution window: t = 0..{}, {} points", cfg.osc_t_end, cfg.osc_n_points));
            if cfg.osc_confirm_t_end > 0.0 {
                c(format!("Confirmation window: t = 0..{}, {} points", cfg.osc_confirm_t_end, cfg.osc_confirm_n_points));
            }
        }
        ObjectiveKind::TimeCourse => {
            c("Objective: time-course match (sum of squared differences)".into());
            c(format!("Target: t = {}..{}, {} points", ctx.target.t_start, ctx.target.t_end, ctx.target.n_points()));
        }
    }
    c(format!("maxPopulationSize = {}", cfg.max_population_size));
    c(format!("species = {}..{}, reactions = {}..{}", cfg.min_species, cfg.max_species, cfg.min_reactions, cfg.max_reactions));
    c(format!(
        "probabilities UniUni/BiUni/UniBi/BiBi = {}/{}/{}/{}",
        cfg.p_uniuni, cfg.p_biuni, cfg.p_unibi, cfg.p_bibi
    ));
    c(format!("eliteFraction = {}", cfg.elite_fraction));
    c(format!("maxInitialRateConstant = {}", cfg.max_initial_rate_constant));
    c(format!(
        "mutation rate/add/delete = {}/{}/{}, rateChangeFraction = {}",
        cfg.p_rate_mutation, cfg.p_add_reaction, cfg.p_delete_reaction, cfg.rate_change_fraction
    ));
    let scores: Vec<String> = r.node_scores.iter().map(|v| format!("{v:.3}")).collect();
    c(format!("Node scores (floating species, state order): {}", scores.join(", ")));

    let mut s = String::new();
    if cfg.add_tellurium_harness {
        s.push_str("import tellurium as te\n\nr = te.loada(\"\"\"\n");
    }
    s.push_str(&h);
    s.push('\n');
    s.push_str(&network_antimony(&r.reduced, &ctx.init));
    s.push('\n');
    let _ = writeln!(s, "//------------------------------------------");
    let _ = writeln!(s, "// Fitness = {:.6} (evolved {:.6}, reduced model {:.6})", r.fitness, r.evolved_fitness, r.reduced_fitness);
    let _ = writeln!(s, "//------------------------------------------");
    let _ = writeln!(s, "// Number of reactions = {} (before reduction {})", r.reduced.reactions.len(), r.best.reactions.len());
    let _ = writeln!(s, "// Number of floating species = {}", r.reduced.n_float);
    let _ = writeln!(s, "// Generations = {} ({:?})", r.generations, r.stop_reason);
    if cfg.add_tellurium_harness {
        let t_end = match cfg.objective {
            ObjectiveKind::Oscillation => cfg.osc_t_end,
            ObjectiveKind::TimeCourse => ctx.target.sim_t_end(),
        };
        let _ = write!(s, "\"\"\")\n\nm = r.simulate(0, {t_end}, 1000)\nr.plot()\n");
    }
    s
}

/// Parse `text` with the `antimony` crate and check that it describes exactly
/// `net`: the same reactions (participants and stoichiometry), boundary
/// species, rate constants, initial values and rate laws.
#[cfg(feature = "antimony")]
pub fn check_antimony(text: &str, net: &Network, init: &[f64]) -> Result<(), String> {
    let loaded = antimony::parse(text);
    if loaded.has_errors() {
        let errs: Vec<String> = loaded.diagnostics.iter().map(|d| d.to_string()).collect();
        return Err(format!("the Antimony does not parse: {}", errs.join("; ")));
    }
    let m = loaded.document.main_module();
    if m.reactions.len() != net.reactions.len() {
        return Err(format!("{} reactions read back, expected {}", m.reactions.len(), net.reactions.len()));
    }
    let multiset = |names: &[u16]| {
        let mut map: BTreeMap<String, f64> = BTreeMap::new();
        for &s in names {
            *map.entry(species_name(s as usize)).or_default() += 1.0;
        }
        map
    };
    let read_side = |ps: &[antimony::model::Participant]| {
        let mut map: BTreeMap<String, f64> = BTreeMap::new();
        for p in ps {
            *map.entry(p.species.clone()).or_default() += m.stoichiometry(p);
        }
        map
    };
    for (j, r) in net.reactions.iter().enumerate() {
        let name = format!("J{j}");
        let rr = m.reaction(&name).ok_or_else(|| format!("reaction {name} missing"))?;
        if read_side(&rr.reactants) != multiset(r.reactants()) || read_side(&rr.products) != multiset(r.products()) {
            return Err(format!("reaction {name} participants differ"));
        }
        let k = m.parameter_value(&format!("k{j}")).ok_or_else(|| format!("k{j} missing"))?;
        if k != r.k {
            return Err(format!("k{j} = {k}, expected {}", r.k));
        }
        let law = rr.kinetic_law.as_ref().ok_or_else(|| format!("{name} has no rate law"))?;
        let v = m.evaluate(law).ok_or_else(|| format!("cannot evaluate the rate law of {name}"))?;
        let expected: f64 = r.k * r.reactants().iter().map(|&s| init[s as usize]).product::<f64>();
        if (v - expected).abs() > 1e-12 * (1.0 + expected.abs()) {
            return Err(format!("rate law of {name} gives {v}, expected {expected}"));
        }
    }
    for (i, &status) in net.status.iter().enumerate() {
        let name = species_name(i);
        if status == SpeciesStatus::Orphan {
            continue;
        }
        let sym = m.symbol(&name).ok_or_else(|| format!("species {name} missing"))?;
        if sym.is_boundary != (status != SpeciesStatus::Float) {
            return Err(format!("species {name}: boundary flag differs"));
        }
        if m.concentration(&name) != Some(init[i]) {
            return Err(format!("species {name}: initial value differs"));
        }
    }
    Ok(())
}

#[cfg(all(test, feature = "antimony"))]
mod tests {
    use super::*;
    use crate::rng::Rng;
    use crate::samples::{PASCAL_INITIAL, pascal_oscillator, random_network};

    #[test]
    fn pascal_oscillator_round_trips() {
        let net = pascal_oscillator();
        let text = network_antimony(&net, &PASCAL_INITIAL);
        check_antimony(&text, &net, &PASCAL_INITIAL).unwrap();
    }

    #[test]
    fn random_networks_round_trip() {
        let mut rng = Rng::new(2024);
        let init: Vec<f64> = (0..12).map(|i| PASCAL_INITIAL[i]).collect();
        for _ in 0..2000 {
            let n_species = rng.range(2, 12) as usize;
            let n_reactions = rng.range(1, 15) as usize;
            let net = random_network(&mut rng, n_species, n_reactions, 50.0);
            let text = network_antimony(&net, &init);
            if let Err(e) = check_antimony(&text, &net, &init) {
                panic!("{e}\n{text}");
            }
        }
    }
}
